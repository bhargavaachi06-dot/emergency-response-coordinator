/**
 * Get localized auth string with graceful fallback to English
 */
export function getAuthText(key, langCode = "en") {
  const code = (langCode || "en").toLowerCase();
  if (AUTH_TRANSLATIONS[code] && AUTH_TRANSLATIONS[code][key]) {
    return AUTH_TRANSLATIONS[code][key];
  }
  // Try English fallback
  if (AUTH_TRANSLATIONS.en && AUTH_TRANSLATIONS.en[key]) {
    return AUTH_TRANSLATIONS.en[key];
  }
  return key;
}
